/**
 * Generates the dish block of the two SQL loaders from `src/lib/menu.ts`.
 *
 *     bun tools/generate-menu-sql.mjs
 *
 * Why a generator for one insert: the seed carries 90 rows of slug, name, Urdu,
 * section, photo and price, and every one of them also lives in the catalogue
 * the app seeds from. Two hand-maintained copies of 90 rows drift — and a
 * drifting seed is how the guest menu ends up showing dishes the owner cannot
 * see in their own admin panel. So the catalogue decides, and this writes the
 * SQL copy of it.
 *
 * It rewrites only section 4 of the file: the 90-row insert and the comment
 * above it. Every other section — tables, indices, the uncategorized parking
 * row, the section upserts, the signature trigger, the verification queries — is
 * hand-written and is left exactly as it is.
 *
 * Writes each target twice: once as `.sql`, and once as a `.txt` twin. The file
 * index hides `.sql`, so the twin is the copy a person can actually open; it is
 * the same SQL behind a five-line header.
 */
import { readFileSync, writeFileSync } from "node:fs";

const SOURCE = "src/lib/menu.ts";
/** Written in this order; both loaders hold the same catalogue. */
const TARGETS = ["supabase/official-menu.sql", "supabase/demo-menu.sql"];

const source = readFileSync(SOURCE, "utf8");

/** `IMG.lemonade` → the Unsplash photo id, so the URL is built in one place. */
const PHOTO_OF_KEY = new Map(
  [...source.matchAll(/([A-Za-z0-9_]+):\s*unsplash\("(photo-[A-Za-z0-9-]+)"/g)].map(
    (match) => [match[1], match[2]],
  ),
);

/** One `makeDish([...])` line, field by field. */
const DISH =
  /makeDish\(\[\s*"([^"]*)",\s*"([^"]*)",\s*"([^"]*)",\s*"([^"]*)",\s*"([^"]*)",\s*IMG\.([A-Za-z0-9_]+),\s*(null|\d+)\s*\]\)/g;

const dishes = [...source.matchAll(DISH)].map((match) => {
  const [, slug, name, urdu, categoryId, summary, photoKey, price] = match;
  const photo = PHOTO_OF_KEY.get(photoKey);
  if (!photo) throw new Error(`${slug}: IMG.${photoKey} is not defined in ${SOURCE}.`);
  return {
    slug,
    name,
    urdu,
    categoryId,
    summary,
    photo,
    price: price === "null" ? null : Number(price),
  };
});

const signatures = new Set(
  [...(source.match(/SIGNATURE_SLUGS = \[([^\]]*)\]/)?.[1] ?? "").matchAll(/"([^"]+)"/g)].map(
    (match) => match[1],
  ),
);

/* ------------------------------------------------------------------ checks -- */

// A regex that silently stopped matching would drop dishes from the seed
// without saying so, which is the exact failure this file exists to prevent, so
// the count is asserted rather than trusted.
if (dishes.length === 0) throw new Error(`${SOURCE}: no makeDish() rows were parsed.`);
const seen = new Set();
for (const dish of dishes) {
  if (seen.has(dish.slug)) throw new Error(`Duplicate slug in ${SOURCE}: ${dish.slug}`);
  seen.add(dish.slug);
  if (!/^[a-z0-9-]+$/.test(dish.slug)) {
    throw new Error(`Slug is not URL-safe: ${dish.slug}`);
  }
}
for (const slug of signatures) {
  if (!seen.has(slug)) throw new Error(`Signature slug not in the catalogue: ${slug}`);
}

/* ------------------------------------------------------------------- build -- */

/** A single-quoted SQL string literal. */
const sql = (value) => `'${String(value).replace(/'/g, "''")}'`;

/** High Tea rows carry no standalone price — they are inside the seat price. */
const highTea = dishes.filter((dish) => dish.price === null).length;
const priced = dishes.length - highTea;

const row = (dish, index) =>
  `  (${[
    sql(dish.slug),
    sql(dish.name),
    sql(dish.urdu),
    sql(dish.categoryId),
    dish.price === null ? "null" : dish.price,
    signatures.has(dish.slug) ? "true" : "false",
    index + 1,
    sql(dish.photo),
    sql(dish.summary),
  ].join(", ")}),`;

const block = [
  "-- ---------------------------------------------------------------------------",
  `-- 4. All ${dishes.length} menu items. The first ${highTea} are live High Tea station`,
  `--    items and the final ${priced} are the priced à la carte menu. Names, sections and`,
  "--    prices are exact, and every row carries the demo photo the guest menu",
  "--    shows — a loaded database should look like the designed menu, not a wall",
  "--    of empty tiles.",
  "--",
  "--    `image` is the Unsplash demo photo, built from the photo id in the rows",
  "--    below so the URL is identical to the one `src/lib/menu.ts` serves. A real",
  "--    upload lives in `image_path` and wins: the update branch leaves `image`",
  "--    alone when the row has an uploaded object, so re-running this loader can",
  "--    never shadow a photo the owner uploaded through the admin panel.",
  "--",
  "--    Generated by tools/generate-menu-sql.mjs — edit src/lib/menu.ts, not this.",
  "-- ---------------------------------------------------------------------------",
  "insert into public.menu_dishes as md",
  "  (slug, name, urdu, category_id, summary, description, notes, pairings, image,",
  "   image_path, price_per_plate, active, featured, demo, sort_order, updated_at)",
  "select d.slug, d.name, d.urdu, d.category_id, d.summary,",
  "       d.summary || ' Prepared fresh by the Janoon kitchen and served with the care befitting the house.',",
  "       '[]'::jsonb, '[]'::jsonb,",
  "       'https://images.unsplash.com/' || d.photo || '?auto=format&fit=crop&w=1200&q=70',",
  "       null, d.price, true, d.featured, true, d.sort_order,",
  "       (extract(epoch from now()) * 1000)::bigint",
  "from (values",
  ...dishes.map(row),
  ") as d(slug, name, urdu, category_id, price, featured, sort_order, photo, summary)",
  "on conflict (slug) do update set",
  "  name = excluded.name,",
  "  urdu = excluded.urdu,",
  "  category_id = excluded.category_id,",
  "  summary = excluded.summary,",
  "  description = excluded.description,",
  "  notes = excluded.notes,",
  "  pairings = excluded.pairings,",
  "  image = case when md.image_path is null then excluded.image else md.image end,",
  "  price_per_plate = excluded.price_per_plate,",
  "  active = true,",
  "  featured = excluded.featured,",
  "  demo = true,",
  "  sort_order = excluded.sort_order,",
  "  updated_at = excluded.updated_at;",
];

/**
 * Swap section 4 of a loader for the freshly built block. The dividers are the
 * boundaries: everything from the rule above the "4." comment to the rule above
 * section 5 is replaced, and the rest of the file is carried over untouched.
 */
function splice(base) {
  const lines = base.split("\n");
  const find = (needle) => {
    const at = lines.findIndex((line) => line.includes(needle));
    if (at === -1) throw new Error(`Section marker not found: ${needle}`);
    let start = at;
    while (start > 0 && !lines[start].startsWith("-- ---")) start -= 1;
    return { start, end: at };
  };
  const four = find("-- 4. All");
  const five = find("-- 5. Four-signature limit");
  if (four.start >= five.start) throw new Error("Section 4 sits after section 5.");
  return [
    ...lines.slice(0, four.start),
    ...block,
    "",
    ...lines.slice(five.start),
  ].join("\n");
}

const official = splice(readFileSync(TARGETS[0], "utf8"));

const header = (file) =>
  [
    "-- ============================================================================",
    `--  THIS IS THE VISIBLE COPY OF ${file}`,
    "--  (the file index hides .sql files, so this .txt twin exists to be opened)",
    "-- ============================================================================",
    "",
    "",
  ].join("\n");

for (const target of TARGETS) {
  writeFileSync(target, official);
  writeFileSync(`${target}.txt`, header(target) + official);
  console.log(`wrote ${target} and ${target}.txt`);
}

console.log(
  `${dishes.length} dishes (${highTea} High Tea, ${priced} priced), ` +
    `${signatures.size} signatures, ${PHOTO_OF_KEY.size} photos`,
);
